#!/usr/bin/env node
// =============================================================================
// StockStudio Pro License API — Ephemeral Local Development Secret Generator
//
// Generates a local `.dev.vars` file (which is gitignored) containing freshly
// generated CSPRNG peppers and an ephemeral Ed25519 keypair for local
// `wrangler dev` testing.
//
// NEVER commits or hardcodes private keys in the repository.
// =============================================================================

import { existsSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { webcrypto } from "node:crypto";

const __dirname = dirname(fileURLToPath(import.meta.url));
const devVarsPath = resolve(__dirname, "..", ".dev.vars");

function randomHex(byteLength = 32) {
  const bytes = new Uint8Array(byteLength);
  webcrypto.getRandomValues(bytes);
  return Array.from(bytes, (b) => b.toString(16).padStart(2, "0")).join("");
}

async function main() {
  const force = process.argv.includes("--force");
  if (existsSync(devVarsPath) && !force) {
    console.log(`[dev:setup] .dev.vars already exists at ${devVarsPath} (use --force to regenerate).`);
    return;
  }

  const keyPair = await webcrypto.subtle.generateKey(
    { name: "Ed25519" },
    true,
    ["sign", "verify"]
  );

  const privateJwk = await webcrypto.subtle.exportKey("jwk", keyPair.privateKey);
  const publicRaw = await webcrypto.subtle.exportKey("raw", keyPair.publicKey);
  const publicBase64 = Buffer.from(publicRaw).toString("base64");

  const licensePepper = randomHex(32);
  const adminPepper = randomHex(32);
  const ipSalt = randomHex(32);
  const mockWebhookSecret = randomHex(32);

  const content = [
    "# Ephemeral local development secrets (auto-generated by scripts/generate-dev-vars.mjs — DO NOT COMMIT)",
    `LICENSE_KEY_PEPPER="${licensePepper}"`,
    `ADMIN_TOKEN_PEPPER="${adminPepper}"`,
    `IP_HASH_SALT="${ipSalt}"`,
    `LICENSE_SIGNING_KID="sspro-ed25519-dev-01"`,
    `LICENSE_SIGNING_PRIVATE_KEY_JWK='${JSON.stringify(privateJwk)}'`,
    `LICENSE_SIGNING_PUBLIC_KEY_BASE64="${publicBase64}"`,
    `BILLING_WEBHOOK_SECRETS_JSON='${JSON.stringify({ mock_provider: mockWebhookSecret })}'`,
    "",
  ].join("\n");

  writeFileSync(devVarsPath, content, { encoding: "utf8", mode: 0o600 });
  console.log(`[dev:setup] Generated ephemeral local .dev.vars (gitignored).`);
  console.log(`[dev:setup] Ephemeral Ed25519 Public Key (base64): ${publicBase64}`);
}

main().catch((err) => {
  console.error("[dev:setup] Failed:", err);
  process.exit(1);
});
